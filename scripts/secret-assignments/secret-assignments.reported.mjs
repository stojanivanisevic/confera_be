// Corpus 1 of secret-assignments.mjs: shapes that MUST be reported.
//
// Every entry is a small file: `file` says how it is read (its name, nothing is written to
// a disk), `text` is its content, and `names` are the names the scan must report, in the
// order of the lines. `syntax` is the way of binding a value to a name that the entry is
// there for; SYNTAXES lists every one that the rule names, and each has at least one entry.
//
// The values are invented and are not valid anywhere. They are written the way a real
// secret is written by mistake: any text, short or long, with no format a scanner of
// formats would know. None starts with a placeholder prefix, which is the point.
//
// `node secret-assignments.mjs --self-test` runs this corpus and the other one.

/** A text of several lines. */
